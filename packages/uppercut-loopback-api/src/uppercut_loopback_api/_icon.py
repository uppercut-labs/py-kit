"""The pixel mark: up to four letters or digits in a 5x7 pixel font, written as a PNG."""

import struct
import zlib
from typing import Sequence

# Each glyph is seven rows of five pixels, top to bottom.
GLYPHS = {
    "A": "01110 10001 10001 11111 10001 10001 10001", "B": "11110 10001 10001 11110 10001 10001 11110",
    "C": "01111 10000 10000 10000 10000 10000 01111", "D": "11110 10001 10001 10001 10001 10001 11110",
    "E": "11111 10000 10000 11110 10000 10000 11111", "F": "11111 10000 10000 11110 10000 10000 10000",
    "G": "01111 10000 10000 10011 10001 10001 01111", "H": "10001 10001 10001 11111 10001 10001 10001",
    "I": "11111 00100 00100 00100 00100 00100 11111", "J": "00111 00010 00010 00010 00010 10010 01100",
    "K": "10001 10010 10100 11000 10100 10010 10001", "L": "10000 10000 10000 10000 10000 10000 11111",
    "M": "10001 11011 10101 10101 10001 10001 10001", "N": "10001 11001 10101 10011 10001 10001 10001",
    "O": "01110 10001 10001 10001 10001 10001 01110", "P": "11110 10001 10001 11110 10000 10000 10000",
    "Q": "01110 10001 10001 10001 10101 10010 01101", "R": "11110 10001 10001 11110 10100 10010 10001",
    "S": "01111 10000 10000 01110 00001 00001 11110", "T": "11111 00100 00100 00100 00100 00100 00100",
    "U": "10001 10001 10001 10001 10001 10001 01110", "V": "10001 10001 10001 10001 01010 01010 00100",
    "W": "10001 10001 10001 10101 10101 10101 01010", "X": "10001 10001 01010 00100 01010 10001 10001",
    "Y": "10001 10001 01010 00100 00100 00100 00100", "Z": "11111 00001 00010 00100 01000 10000 11111",
    "0": "01110 10001 10011 10101 11001 10001 01110", "1": "00100 01100 00100 00100 00100 00100 01110",
    "2": "01110 10001 00001 00010 00100 01000 11111", "3": "11110 00001 00001 01110 00001 00001 11110",
    "4": "00010 00110 01010 10010 11111 00010 00010", "5": "11111 10000 11110 00001 00001 10001 01110",
    "6": "01110 10000 10000 11110 10001 10001 01110", "7": "11111 00001 00010 00100 01000 01000 01000",
    "8": "01110 10001 10001 01110 10001 10001 01110", "9": "01110 10001 10001 01111 00001 00001 01110",
}


def pixel_mark_png(text: str, size: int, background: Sequence[int], foreground: Sequence[int]) -> bytes:
    """A square RGB PNG, `size` pixels wide, with `text` centered in the 5x7 pixel font.

    Only A-Z and 0-9 are drawn, at most four of them; lower case is raised. Text with none
    of those characters gives a plain tile. No image library is needed.
    """
    text = "".join(ch for ch in text.upper() if ch in GLYPHS)[:4]
    columns = max(1, len(text)) * 6 - 1
    cell = max(1, size // (columns + 7))
    ox, oy = (size - columns * cell) // 2, (size - 7 * cell) // 2
    lit = set()
    for i, ch in enumerate(text):
        for r, row in enumerate(GLYPHS[ch].split()):
            for c, bit in enumerate(row):
                if bit == "1":
                    lit.add((i * 6 + c, r))
    bg, fg = bytes(background), bytes(foreground)
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            gx, gy = x - ox, y - oy
            row += fg if gx >= 0 and gy >= 0 and (gx // cell, gy // cell) in lit else bg
        rows.append(bytes(row))

    def chunk(kind: bytes, body: bytes) -> bytes:
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(rows), 9))
            + chunk(b"IEND", b""))
